#[test]
fn decodes_a_real_bundle_directory_block() {
    let out = lz4::decompress(&COMPRESSED, Some(UNCOMPRESSED.len())).expect("decode");
    assert_eq!(out, UNCOMPRESSED.to_vec());
}

#[test]
fn recompresses_and_still_decodes() {
    let packed = lz4::compress(&UNCOMPRESSED);
    let back = lz4::decompress(&packed, Some(UNCOMPRESSED.len())).expect("decode own output");
    assert_eq!(back, UNCOMPRESSED.to_vec());
    // The game's LZ4HC block is 174 bytes; a greedy search must stay far closer
    // to that than to the 291-byte expansion.
    assert!(
        packed.len() < UNCOMPRESSED.len(),
        "compressed to {} bytes, larger than the {}-byte input",
        packed.len(),
        UNCOMPRESSED.len()
    );
}

#[test]
fn rejects_a_corrupted_block() {
    let mut bad = COMPRESSED;
    // Flip a byte in the middle of the token stream.
    let mid = bad.len() / 2;
    bad[mid] ^= 0xFF;
    // Either it fails outright or it decodes to something different; what it
    // must not do is claim the original contents.
    if let Ok(out) = lz4::decompress(&bad, Some(UNCOMPRESSED.len())) {
        assert_ne!(out, UNCOMPRESSED.to_vec());
    }
}
